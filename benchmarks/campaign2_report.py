from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]


def read(name):
    return json.loads((ROOT/name).read_text())


def frac(obj):
    return Fraction(int(obj['num']),int(obj['den']))


def exact(obj):
    return obj['num']+'/'+obj['den']


def directed(value, places=9, upper=False):
    scaled=value.numerator*10**places
    quotient=(scaled+value.denominator-1)//value.denominator if upper else scaled//value.denominator
    return str(quotient//10**places)+'.'+str(quotient%10**places).zfill(places)


